    /**
     * Tạo một Node SVGPath từ tên Bootstrap Icon.
     * @param name Tên icon
     * @param targetSize Kích thước hiển thị (px)
     * @param color Màu sắc icon
     */
    public static Node icon(String name, double targetSize, Paint color) {
        String path = ICONS.getOrDefault(name, ICONS.get("dashboard"));
        SVGPath svg = new SVGPath();
        svg.setContent(path);
        svg.setFill(color);

        // Chuẩn hóa kích thước khung Bootstrap (16x16) sang targetSize
        double scale = targetSize / 16.0;
        svg.setScaleX(scale);
        svg.setScaleY(scale);

        StackPane container = new StackPane(svg);
        container.setPrefSize(targetSize, targetSize);
        container.setMinSize(targetSize, targetSize);
        container.setMaxSize(targetSize, targetSize);
        container.setAlignment(Pos.CENTER);
        return container;
    }

    /**
     * Tạo một mục Menu bên trái với Icon Bootstrap sắc nét.
     */
    public static Node navItem(String iconName, String labelText, Paint iconColor) {
        Node ic = icon(iconName, 16, iconColor);
        Label text = new Label(labelText);
        text.getStyleClass().add("nav-text");
        HBox box = new HBox(12, ic, text);
        box.setAlignment(Pos.CENTER_LEFT);
        return box;
    }
